import { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { backend, type BackendCapabilities, type EvaluationSummary } from '../../api';
import { Badge, Callout, Empty, Tip, fmtDate } from '../../components/ui';
import { AGENT_INFO, WORKFLOW_STATUS } from '../../lib/labels';
import { fmtPoints } from '../../lib/viewModel';
import type { AgentName } from '../../api/types';

function GradeCell({ e }: { e: EvaluationSummary }) {
  if (e.reviewed_points !== null) return <div className="mini-grade ink">{fmtPoints(e.reviewed_points)}<span className="muted small"> / {fmtPoints(e.max_points)}</span><div className="tiny c-muted" style={{ fontFamily: 'var(--sans)', fontWeight: 600 }}>Approved</div></div>;
  if (e.proposed_points !== null) return <div className="mini-grade pencil">{fmtPoints(e.proposed_points)}<span className="muted small"> / {fmtPoints(e.max_points)}</span><div className="tiny" style={{ fontFamily: 'var(--sans)', fontWeight: 600 }}>AI proposed</div></div>;
  return <div className="mini-grade withheld">Grade withheld<div className="tiny c-muted">{e.assessed_weight_percent}% assessed</div></div>;
}

export default function EvaluationsList({ caps }: { caps: BackendCapabilities | null }) {
  const [rows, setRows] = useState<EvaluationSummary[] | null>(null);
  const [err, setErr] = useState<string | null>(null);
  useEffect(() => { backend.listEvaluations().then(setRows).catch((e) => setErr(String(e.message || e))); }, []);
  const needs = rows?.filter((r) => r.assessment_status !== 'TEACHER_REVIEWED').length ?? 0;
  return (
    <div className="page">
      <div className="page-head">
        <div>
          <h1>Evaluations</h1>
          <p>{rows ? (needs ? `${needs} of ${rows.length} evaluations still need your review before their marks are final.` : 'Every evaluation has been reviewed.') : 'Loading evaluations…'}</p>
        </div>
        <Link to="/new" className="btn primary">New evaluation</Link>
      </div>
      {caps?.kind === 'mock' && (
        <div className="banner"><strong>Demo data.</strong> These evaluations were generated by the real ProjectIQ engine from synthetic agent outputs for fictional projects. Teacher decisions are saved in this browser.</div>
      )}
      {err && <Callout tone="bad" title="Evaluations could not be loaded">{err}</Callout>}
      <div className="panel" style={{ padding: 0 }}>
        <div className="eval-row" style={{ paddingTop: 10, paddingBottom: 10, background: 'var(--surface-2)', borderTopLeftRadius: 14, borderTopRightRadius: 14 }}>
          <span className="small muted">Project and students</span><span className="small muted">Status</span><span className="small muted">Agents</span><span className="small muted" style={{ textAlign: 'right' }}>Grade</span>
        </div>
        {rows && !rows.length && <Empty title="No evaluations yet">Start one from <Link to="/new">New evaluation</Link>.</Empty>}
        {rows?.map((e) => {
          const ws = WORKFLOW_STATUS[e.workflow_status] ?? { label: e.workflow_status, tone: 'muted', explain: '' };
          const reviewed = e.assessment_status === 'TEACHER_REVIEWED';
          return (
            <Link key={e.id} to={`/evaluations/${e.id}`} className="eval-row">
              <div>
                <h3 style={{ fontSize: 16.5 }}>{e.title}</h3>
                <div className="small muted">{e.students.join(', ') || 'Students not recorded'}{e.course ? `, ${e.course}` : ''}</div>
                <div className="tiny c-muted">{e.submission_id}, evaluated {fmtDate(e.evaluated_utc)}{!e.has_repository && ", report only"}</div>
              </div>
              <div className="stack" style={{ gap: 6 }}>
                <span>{reviewed ? <Badge tone="ink">Marks approved</Badge> : <Tip text={ws.explain}><Badge tone={ws.tone}>{ws.label}</Badge></Tip>}</span>
                <span className="tiny muted">Reviewed {e.reviewed_weight_percent}% of the weight</span>
              </div>
              <div className="agent-dots">
                {(Object.keys(e.agent_statuses) as AgentName[]).map((a) => (
                  <span key={a} className={`agent-dot ${e.agent_statuses[a]}`} title={`${AGENT_INFO[a].name}: ${e.agent_statuses[a]}`}>{AGENT_INFO[a].name}</span>
                ))}
              </div>
              <GradeCell e={e} />
            </Link>
          );
        })}
      </div>
    </div>
  );
}
