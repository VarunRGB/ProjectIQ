import { Link, NavLink, useParams } from 'react-router-dom';
import type { BackendCapabilities } from '../../api';
import { Badge, Callout, ProvenanceBadge, Tip, fmtDate, fmtDuration, shortSha } from '../../components/ui';
import { WORKFLOW_STATUS } from '../../lib/labels';
import { useEvaluation } from '../../lib/useEvaluation';
import Overview from './Overview';
import Grading from './Grading';
import ExecutionerTab from './ExecutionerTab';
import ResearchTab from './ResearchTab';
import IntegrityTab from './IntegrityTab';
import SummaryTab from './SummaryTab';
import EvidenceTab from './EvidenceTab';
import ActivityTab from './ActivityTab';
import FormatTab from './FormatTab';

export default function ResultsPage({ caps }: { caps: BackendCapabilities | null }) {
  const { id, tab = 'overview' } = useParams();
  const { rec, vm, error, setReview, reload } = useEvaluation(id);
  if (error) return <div className="page"><Callout tone="bad" title="This evaluation could not be opened">{error}</Callout></div>;
  if (!rec || !vm) return <div className="page"><p className="muted">Loading evaluation…</p></div>;
  const r = rec.result;
  const sub = r.submission;
  const ws = WORKFLOW_STATUS[r.workflow_status];
  const a = vm.assessment;
  const toReview = a.criteria.filter((c) => c.status !== 'EXCLUDED' && c.status !== 'TEACHER_REVIEWED').length;
  const base = `/evaluations/${id}`;
  const tabs: [string, string, number | null, boolean?][] = [
    ['overview', 'Overview', null],
    ['grading', 'Grading', toReview, toReview > 0],
    ['executioner', 'Executioner', null],
    ['research', 'Research', null],
    ['integrity', 'Integrity', null],
    ['format', 'Format', null],
    ['summary', 'Report summary', null],
    ['evidence', 'Evidence', rec.evidence?.items.length ?? null],
    ['activity', 'Activity', null],
  ];
  return (
    <div className="page">
      {rec.source === 'MOCK_FIXTURE' && (
        <div className="banner"><strong>Demo data.</strong> Generated by the real ProjectIQ engine from synthetic agent outputs for a fictional project. It is not an analysis of any uploaded file.</div>
      )}
      <div className="page-head">
        <div style={{ minWidth: 0 }}>
          <div className="row small muted" style={{ marginBottom: 6 }}>
            <Link to="/">Evaluations</Link><span aria-hidden>/</span><span>{sub.id}</span>
          </div>
          <h1>{sub.project_title}</h1>
          <p>
            {rec.meta.students?.length ? rec.meta.students.join(', ') : 'Students not recorded'}
            {rec.meta.course ? `, ${rec.meta.course}` : ''}
          </p>
          <div className="row small" style={{ marginTop: 10, gap: 14 }}>
            <Tip text={ws.explain}><Badge tone={ws.tone}>{ws.label}</Badge></Tip>
            <Tip text={r.collection_mode === 'LIVE' ? 'Agents ran in this evaluation.' : 'Agent results were imported from earlier runs and re-verified against their receipts.'}>
              <Badge tone={r.collection_mode === 'LIVE' ? 'good' : 'warn'}>{r.collection_mode === 'LIVE' ? 'Live collection' : 'Imported evidence'}</Badge>
            </Tip>
            {vm.provenance.acknowledged && <ProvenanceBadge p="IMPORTED_ACKNOWLEDGED" />}
            <span className="muted">Report <code>{sub.report_name}</code></span>
            {sub.repository_url ? (
              <span className="muted">Repository <a href={sub.repository_url} target="_blank" rel="noreferrer">{sub.repository_url.replace('https://github.com/', '')}</a>{r.agents.executioner.details?.source?.commit_sha && <> at <code>{shortSha(r.agents.executioner.details.source.commit_sha)}</code></>}</span>
            ) : <Badge tone="muted">Report only, no repository</Badge>}
            <span className="muted">{rec.meta.evaluated_utc ? `Evaluated ${fmtDate(rec.meta.evaluated_utc)} in ` : 'Run time '}{fmtDuration(rec.meta.elapsed_seconds ?? r.elapsed_seconds)}</span>
          </div>
        </div>
        <div className="row">
          <Link className="btn" to={`${base}/report`} target="_blank">Open report</Link>
          <Link className="btn primary" to={`${base}/grading`}>{toReview ? `Review ${toReview} criteria` : 'View grading'}</Link>
        </div>
      </div>

      <nav className="tabs" aria-label="Evaluation sections">
        {tabs.map(([key, label, count, warn]) => (
          <NavLink key={key} to={key === 'overview' ? base : `${base}/${key}`} end className={() => (tab === key ? 'active' : '')}>
            {label}{count !== null && count > 0 && <span className={`tab-count ${warn ? 'warn' : ''}`}>{count}</span>}
          </NavLink>
        ))}
      </nav>

      {tab === 'overview' && <Overview vm={vm} base={base} />}
      {tab === 'grading' && <Grading vm={vm} setReview={setReview} caps={caps} reload={reload} />}
      {tab === 'executioner' && <ExecutionerTab vm={vm} />}
      {tab === 'research' && <ResearchTab vm={vm} />}
      {tab === 'integrity' && <IntegrityTab vm={vm} />}
      {tab === 'format' && <FormatTab f={r.ieee_format} />}
      {tab === 'summary' && <SummaryTab vm={vm} />}
      {tab === 'evidence' && <EvidenceTab vm={vm} />}
      {tab === 'activity' && <ActivityTab vm={vm} />}
    </div>
  );
}
