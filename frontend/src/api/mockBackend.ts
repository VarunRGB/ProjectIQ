/**
 * Temporary mock backend. Every evaluation it returns is a fixture produced by the
 * REAL projectiq_core pipeline (tools/generate_fixtures.py) from synthetic native
 * agent outputs. New runs replay a matching fixture with a simulated timeline; they
 * do not analyse the uploaded files, and the UI says so.
 *
 * Replace with HttpBackend (VITE_BACKEND=http) once the local bridge is wired.
 */
import type { Backend, BackendCapabilities, EvaluationSummary, ReassessResult } from './backend';
import { emptyReview } from './backend';
import type {
  AgentName, EvaluationRecord, EvaluationRequest, Rubric, RunEvent, RunStage, RunStatus,
  TeacherDecisionEntry, TeacherReview, UnifiedResult,
} from './types';

type Fixture = {
  scenario: string;
  meta: EvaluationRecord['meta'];
  result: UnifiedResult;
  evidence: EvaluationRecord['evidence'];
  decisions: EvaluationRecord['decisions'];
  report_text: string;
};

const loaders: Record<string, () => Promise<{ default: unknown }>> = {
  campusconnect: () => import('../mock/fixtures/campusconnect.json'),
  meditrack: () => import('../mock/fixtures/meditrack.json'),
  irrigation: () => import('../mock/fixtures/irrigation.json'),
};

const REVIEW_KEY = (id: string) => `projectiq.review.${id}.v1`;
const RUNS_KEY = 'projectiq.mockRuns.v1';

function readJSON<T>(key: string, fallback: T): T {
  try { const raw = localStorage.getItem(key); return raw ? (JSON.parse(raw) as T) : fallback; } catch { return fallback; }
}
function writeJSON(key: string, value: unknown) {
  try { localStorage.setItem(key, JSON.stringify(value)); } catch { /* storage unavailable: keep in memory */ }
}

interface MockRun {
  run_id: string; evaluation_id: string; scenario: string; title: string; submission_id: string;
  started_at: number; script: { at: number; stage: RunStage; agent?: AgentName | 'rubric' | 'format'; state?: string; message: string; level: RunEvent['level'] }[];
  total_ms: number; cancelled?: boolean; request: Pick<EvaluationRequest, 'title' | 'submission_id' | 'students' | 'course' | 'rubric' | 'repository_url' | 'report_file_name'> & { mode: string | null };
}

const now = () => Date.now();

export class MockBackend implements Backend {
  private cache = new Map<string, Fixture>();
  private reviews = new Map<string, TeacherReview>();

  async capabilities(): Promise<BackendCapabilities> {
    return {
      name: 'Demo backend (generated fixtures)', kind: 'mock',
      liveExecutionerModes: ['STATIC'], importExecutionerResults: true, onlineResearchVerification: true,
      integrityReferenceUpload: true, aiDetection: 'AVAILABLE', rubricReassessment: true,
      persistsTeacherDecisions: 'BROWSER_ONLY',
      notes: [
        'Results are fixtures generated by the real ProjectIQ engine from synthetic agent outputs.',
        'New evaluations replay a matching fixture; uploaded files are not analysed.',
        'Teacher decisions are saved in this browser only.',
      ],
    };
  }

  private async fixture(scenario: string): Promise<Fixture> {
    if (!this.cache.has(scenario)) {
      const mod = await loaders[scenario]();
      this.cache.set(scenario, mod.default as Fixture);
    }
    return this.cache.get(scenario)!;
  }

  private runs(): MockRun[] { return readJSON<MockRun[]>(RUNS_KEY, []); }

  private review(id: string): TeacherReview {
    if (!this.reviews.has(id)) this.reviews.set(id, readJSON<TeacherReview>(REVIEW_KEY(id), emptyReview()));
    return this.reviews.get(id)!;
  }
  private storeReview(id: string, r: TeacherReview): TeacherReview {
    this.reviews.set(id, r); writeJSON(REVIEW_KEY(id), r); return r;
  }

  private async record(id: string): Promise<EvaluationRecord> {
    const run = this.runs().find((r) => r.evaluation_id === id);
    const scenario = run ? run.scenario : id.replace(/^demo-/, '');
    if (!loaders[scenario]) throw new Error('EVALUATION_NOT_FOUND');
    const fx = await this.fixture(scenario);
    let result = fx.result;
    let meta = fx.meta;
    if (run) {
      result = structuredClone(fx.result);
      result.submission = { ...result.submission, project_title: run.title, id: run.submission_id };
      meta = { ...fx.meta, students: run.request.students.length ? run.request.students : fx.meta.students, course: run.request.course || fx.meta.course, evaluated_utc: new Date(run.started_at + run.total_ms).toISOString() };
    }
    return { id, result, evidence: fx.evidence, decisions: fx.decisions, reportText: fx.report_text, meta, review: this.review(id), source: 'MOCK_FIXTURE' };
  }

  async listEvaluations(): Promise<EvaluationSummary[]> {
    const ids = ['demo-campusconnect', 'demo-meditrack', 'demo-irrigation'];
    const done = this.runs().filter((r) => !r.cancelled && now() - r.started_at >= r.total_ms).map((r) => r.evaluation_id);
    const out: EvaluationSummary[] = [];
    for (const id of [...done.reverse(), ...ids]) {
      const rec = await this.record(id);
      const { recompute } = await import('../lib/scoring');
      const a = recompute({ base: rec.result.assessment, rubric: rec.review.rubricOverride ?? rec.result.rubric, teacher: rec.review.decisions, invalidated: rec.review.pendingReassessment });
      out.push({
        id, title: rec.result.submission.project_title, submission_id: rec.result.submission.id, students: rec.meta.students ?? [],
        course: rec.meta.course, evaluated_utc: rec.meta.evaluated_utc, workflow_status: rec.result.workflow_status,
        assessment_status: a.status, max_points: a.max_points, proposed_points: a.proposed_points, reviewed_points: a.reviewed_points,
        assessed_weight_percent: a.assessed_weight_percent, reviewed_weight_percent: a.reviewed_weight_percent,
        has_repository: !!rec.result.submission.repository_url,
        agent_statuses: Object.fromEntries(Object.entries(rec.result.agents).map(([k, v]) => [k, v.status])), source: rec.source,
      });
    }
    return out;
  }

  getEvaluation(id: string) { return this.record(id); }

  async startEvaluation(req: EvaluationRequest): Promise<{ run_id: string }> {
    const scenario = !req.repository_url ? 'irrigation' : (req.executioner && req.executioner.mode !== 'STATIC') || req.executioner_import_file ? 'campusconnect' : 'meditrack';
    const run_id = 'run-' + Math.random().toString(36).slice(2, 10);
    const evaluation_id = `mock-${scenario}-${run_id.slice(4)}`;
    const script: MockRun['script'] = [];
    let t = 400;
    const step = (dt: number, e: Omit<MockRun['script'][number], 'at'>) => { t += dt; script.push({ at: t, ...e }); };
    step(0, { stage: 'queued', message: 'Submission received; private report snapshot saved with its SHA-256.', level: 'info' });
    step(500, { stage: 'format', agent: 'format', state: 'running', message: 'Checking the report against IEEE formatting conventions.', level: 'info' });
    step(1400, { stage: 'format', agent: 'format', state: 'done', message: 'Format check finished.', level: 'success' });
    step(200, { stage: 'summarizer', agent: 'summarizer', state: 'running', message: 'Extracting report text and key sentences (no model call).', level: 'info' });
    step(1500, { stage: 'summarizer', agent: 'summarizer', state: 'done', message: 'Summary extracted.', level: 'success' });
    step(300, { stage: 'integrity', agent: 'integrity', state: 'running', message: req.reference_files.length ? `Comparing the report with ${req.reference_files.length} reference document(s).` : 'No references uploaded: similarity will be unavailable, not zero.', level: req.reference_files.length ? 'info' : 'warn' });
    step(2400, { stage: 'integrity', agent: 'integrity', state: 'running', message: 'Scoring passages of the student’s own writing for AI-like text.', level: 'info' });
    step(1800, { stage: 'integrity', agent: 'integrity', state: scenario === 'campusconnect' ? 'done' : 'partial', message: scenario === 'campusconnect' ? 'Integrity complete.' : 'Integrity finished with limited coverage.', level: scenario === 'campusconnect' ? 'success' : 'warn' });
    if (req.research_required) {
      step(300, { stage: 'research', agent: 'research', state: 'running', message: 'Extracting bibliography and in-text citations.', level: 'info' });
      if (req.verify_research) step(2200, { stage: 'research', agent: 'research', state: 'running', message: 'Checking paper identities online (opt-in).', level: 'info' });
      if (scenario === 'meditrack') step(2600, { stage: 'research', agent: 'research', state: 'failed', message: 'Research agent failed: metadata lookup timed out. Other results are kept.', level: 'error' });
      else step(2200, { stage: 'research', agent: 'research', state: 'done', message: 'Research report generated.', level: 'success' });
    } else step(100, { stage: 'research', agent: 'research', state: 'skipped', message: 'Research is not part of this rubric; agent skipped.', level: 'info' });
    if (req.repository_url) {
      const mode = req.executioner?.mode ?? 'STATIC';
      step(300, { stage: 'executioner', agent: 'executioner', state: 'running', message: 'Pinning the repository commit and indexing files.', level: 'info' });
      step(1600, { stage: 'executioner', agent: 'executioner', state: 'running', message: 'Discovering technologies, routes and features; planning tests.', level: 'info' });
      step(1600, { stage: 'executioner', agent: 'executioner', state: 'running', message: 'Running static code-quality analysis.', level: 'info' });
      if (mode === 'STATIC') step(900, { stage: 'executioner', agent: 'executioner', state: 'partial', message: 'STATIC mode: no tests executed. Functional marks need verified runs.', level: 'warn' });
      else step(1400, { stage: 'executioner', agent: 'executioner', state: 'partial', message: `Demo: an existing ${mode} result is bundled as acknowledged imported evidence.`, level: 'warn' });
    } else step(100, { stage: 'executioner', agent: 'executioner', state: 'skipped', message: 'Report-only submission: no repository to inspect.', level: 'info' });
    step(400, { stage: 'evidence', message: 'Verifying agent receipts and building the evidence bundle.', level: 'info' });
    step(600, { stage: 'rubric', agent: 'rubric', state: 'running', message: 'Rubric model proposing levels in small batches, citing evidence.', level: 'info' });
    step(2600, { stage: 'rubric', agent: 'rubric', state: 'done', message: 'Proposals validated; unsupported ones were deferred to you.', level: 'success' });
    step(300, { stage: 'done', message: 'Evaluation ready for review.', level: 'success' });
    const run: MockRun = {
      run_id, evaluation_id, scenario, title: req.title, submission_id: req.submission_id, started_at: now(), script, total_ms: t,
      request: { title: req.title, submission_id: req.submission_id, students: req.students, course: req.course, rubric: req.rubric, repository_url: req.repository_url, report_file_name: req.report_file_name, mode: req.executioner?.mode ?? null },
    };
    writeJSON(RUNS_KEY, [...this.runs(), run]);
    return { run_id };
  }

  async getRun(runId: string): Promise<RunStatus> {
    const run = this.runs().find((r) => r.run_id === runId);
    if (!run) throw new Error('RUN_NOT_FOUND');
    const elapsed = Math.min(now() - run.started_at, run.total_ms);
    const seen = run.script.filter((e) => e.at <= elapsed);
    const agents: RunStatus['agents'] = {
      format: { state: 'waiting' }, summarizer: { state: 'waiting' }, integrity: { state: 'waiting' }, research: { state: 'waiting' },
      executioner: { state: 'waiting' }, rubric: { state: 'waiting' },
    };
    const started: Record<string, number> = {};
    for (const e of seen) if (e.agent && e.state) {
      if (!(e.agent in started)) started[e.agent] = e.at;
      agents[e.agent] = { state: e.state as any, detail: e.message, elapsed_ms: e.at - started[e.agent] };
    }
    for (const [k, v] of Object.entries(agents)) if (v.state === 'running') v.elapsed_ms = elapsed - started[k];
    const last = seen[seen.length - 1];
    const finished = elapsed >= run.total_ms;
    return {
      run_id: runId, evaluation_id: finished && !run.cancelled ? run.evaluation_id : null, title: run.title,
      started_at: new Date(run.started_at).toISOString(), elapsed_ms: elapsed, stage: run.cancelled ? 'failed' : last?.stage ?? 'queued',
      state: run.cancelled ? 'CANCELLED' : finished ? 'COMPLETED' : 'RUNNING', agents,
      events: seen.map((e) => ({ at_ms: e.at, stage: e.stage, agent: e.agent, message: e.message, level: e.level })),
    };
  }

  async cancelRun(runId: string) {
    writeJSON(RUNS_KEY, this.runs().map((r) => (r.run_id === runId ? { ...r, cancelled: true, total_ms: now() - r.started_at } : r)));
  }

  async saveTeacherDecision(id: string, entry: TeacherDecisionEntry) {
    const r = structuredClone(this.review(id));
    const had = r.decisions[entry.criterion_id];
    r.decisions[entry.criterion_id] = entry;
    r.pendingReassessment = r.pendingReassessment.filter((c) => c !== entry.criterion_id);
    r.history.unshift({ at: entry.decided_utc, kind: entry.basis === 'APPROVED_PROPOSAL' ? 'APPROVED' : entry.basis === 'OVERRIDE' ? 'OVERRIDDEN' : 'SCORED', criterion_id: entry.criterion_id,
      summary: (had ? 'Updated' : entry.basis === 'APPROVED_PROPOSAL' ? 'Approved' : entry.basis === 'OVERRIDE' ? 'Overrode' : 'Scored') + ` ${entry.criterion_id}${entry.level_id ? ' at level ' + entry.level_id : ''}` });
    return this.storeReview(id, r);
  }

  async clearTeacherDecision(id: string, criterionId: string) {
    const r = structuredClone(this.review(id));
    delete r.decisions[criterionId];
    r.history.unshift({ at: new Date().toISOString(), kind: 'CLEARED', criterion_id: criterionId, summary: `Returned ${criterionId} to the AI proposal` });
    return this.storeReview(id, r);
  }

  async updateRubric(id: string, rubric: Rubric, invalidated: string[]) {
    const r = structuredClone(this.review(id));
    r.rubricOverride = rubric;
    r.pendingReassessment = [...new Set([...r.pendingReassessment, ...invalidated])];
    for (const cid of invalidated) delete r.decisions[cid];
    r.history.unshift({ at: new Date().toISOString(), kind: 'REWEIGHTED', summary: invalidated.length ? `Rubric updated; ${invalidated.length} criterion(s) need reassessment` : `Weights or marks updated (total ${rubric.total_points}); no agents rerun` });
    return this.storeReview(id, r);
  }

  async reassess(id: string, criterionIds: string[], opts: { retryDeferred: boolean }): Promise<ReassessResult> {
    await new Promise((res) => setTimeout(res, 1400));
    const rec = await this.record(id);
    const r = structuredClone(this.review(id));
    const messages: string[] = [];
    for (const cid of criterionIds) {
      const base = rec.result.assessment.criteria.find((c) => c.id === cid);
      if (r.pendingReassessment.includes(cid)) {
        r.pendingReassessment = r.pendingReassessment.filter((c) => c !== cid);
        messages.push(base?.fraction != null ? `${base.title}: the rubric model returned a proposal for the updated criterion.` : `${base?.title ?? cid}: still deferred; score it from the evidence.`);
        r.history.unshift({ at: new Date().toISOString(), kind: 'REASSESSED', criterion_id: cid, summary: `Reassessed ${cid} (rubric model only)` });
      } else if (opts.retryDeferred) {
        r.retryRequested = [...new Set([...r.retryRequested, cid])];
        messages.push(`${base?.title ?? cid}: retry completed. The evidence gate still applies, so the criterion remains deferred to you.`);
        r.history.unshift({ at: new Date().toISOString(), kind: 'RETRY_REQUESTED', criterion_id: cid, summary: `Retried the deferred judgment for ${cid}` });
      }
    }
    return { updated: this.storeReview(id, r), messages };
  }

  async resetReview(id: string) { return this.storeReview(id, emptyReview()); }
}
